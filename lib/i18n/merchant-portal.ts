const localeOverrides: Record<Exclude<MerchantPortalLanguage, "en">, MessageCatalog> =
  Object.fromEntries(
    Object.entries(localeOverridesRaw).map(([language, messages]) => [
      language,
      { ...enMessages, ...messages },
    ]),
  ) as Record<Exclude<MerchantPortalLanguage, "en">, MessageCatalog>;

function warnMissingLocaleKeys() {
  if (typeof window !== "undefined" || process.env.NODE_ENV === "test") {
    return;
  }

  const englishKeys = Object.keys(enMessages);
  for (const language of Object.keys(localeOverrides) as Array<
    Exclude<MerchantPortalLanguage, "en">
  >) {
    const missing = englishKeys.filter((key) => !(key in localeOverrides[language]));
    if (missing.length) {
      console.warn(
        `[merchant-i18n] ${language} is missing ${missing.length} keys; falling back to English.`,
      );
    }
  }
}

warnMissingLocaleKeys();

function interpolate(template: string, variables?: MessageVariables) {
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => {
    const value = variables[key];
    return value === undefined ? "" : String(value);
  });
}

export function translatePortalMessage(
  language: MerchantPortalLanguage,
  key: string,
  variables?: MessageVariables,
) {
  const localized =
    language === "en"
      ? enMessages[key]
      : (localeOverrides[language]?.[key] ?? enMessages[key]);

  return interpolate(localized ?? key, variables);
}
