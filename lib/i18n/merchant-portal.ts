export function normalizePortalLanguage(value?: string | null): MerchantPortalLanguage {
  if (value && SUPPORTED_PORTAL_LANGUAGES.includes(value as MerchantPortalLanguage)) {
    return value as MerchantPortalLanguage;
  }

  return DEFAULT_PORTAL_LANGUAGE;
}

